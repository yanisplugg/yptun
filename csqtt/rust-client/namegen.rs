fn female_surname(value: &str) -> String {
    if let Some(stem) = value
        .strip_suffix("ий")
        .or_else(|| value.strip_suffix("ый"))
        .or_else(|| value.strip_suffix("ой"))
    {
        return format!("{stem}ая");
    }
    if ["ов", "ев", "ин", "ын", "ёв"]
        .iter()
        .any(|suffix| value.ends_with(suffix))
    {
        return format!("{value}а");
    }
    value.to_owned()
}

pub fn generate_name() -> String {
    let mut rng = rand::rng();
    let female = rng.random_bool(0.5);
    let first = if female {
        FEMALE[rng.random_range(0..FEMALE.len())]
    } else {
        MALE[rng.random_range(0..MALE.len())]
    };
    if rng.random_bool(0.3) {
        return first.to_owned();
    }
    let last = LAST[rng.random_range(0..LAST.len())];
    if female {
        format!("{first} {}", female_surname(last))
    } else {
        format!("{first} {last}")
    }
}

