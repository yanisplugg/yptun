#[test]
fn split_host_port_ignores_trailing_path() {
    let hp = |h: &str, p: i32| Some((h.to_string(), p));
    assert_eq!(split_host_port("1.2.3.4:443/?type=tcp"), hp("1.2.3.4", 443));
    assert_eq!(split_host_port("1.2.3.4:443/"), hp("1.2.3.4", 443));
    assert_eq!(split_host_port("a.com:8443"), hp("a.com", 8443));
    assert_eq!(
        split_host_port("[2001:db8::1]:443/path"),
        hp("2001:db8::1", 443)
    );
}
